# Diagnose directional disagreement between the KNF rule model and LiDAR GBM.
#
# Requires `dev/gutcheck_validation_record.R`. The output identifies where one
# method agrees with the recorded field-stage call and the other does not, then
# summarizes LiDAR structural metrics and probability uncertainty. It is a
# diagnostic for field review and data QA, not a causal analysis or independent
# accuracy assessment.

.normalized_entropy <- function(probabilities) {
  probabilities <- base::as.matrix(probabilities)
  -base::rowSums(ifelse(probabilities > 0, probabilities * base::log(probabilities), 0)) /
    base::log(base::ncol(probabilities))
}

.probability_margin <- function(probabilities) {
  probabilities <- base::as.matrix(probabilities)
  base::apply(probabilities, 1L, function(x) {
    ordered <- base::sort(x, decreasing = TRUE)
    ordered[1L] - ordered[2L]
  })
}

.disagreement_case_type <- function(field_class, rule_class, lidar_class) {
  base::ifelse(
    rule_class == field_class & lidar_class == field_class,
    "Both correct",
    base::ifelse(
      lidar_class == field_class & rule_class != field_class,
      "LiDAR correct; rule wrong",
      base::ifelse(
        rule_class == field_class & lidar_class != field_class,
        "Rule correct; LiDAR wrong",
        base::ifelse(
          rule_class == lidar_class,
          "Both wrong; same call",
          "Both wrong; different calls"
        )
      )
    )
  )
}

.disagreement_summary <- function(data, grouping) {
  groups <- base::split(data, interaction(data[, grouping, drop = FALSE], drop = TRUE, lex.order = TRUE))
  base::do.call(base::rbind, base::lapply(groups, function(part) {
    key <- part[1L, grouping, drop = FALSE]
    base::cbind(
      key, n = base::nrow(part),
      mean_lidar_confidence = base::mean(part$lidar_confidence),
      median_lidar_confidence = stats::median(part$lidar_confidence),
      mean_entropy = base::mean(part$lidar_entropy),
      median_entropy = stats::median(part$lidar_entropy),
      mean_margin = base::mean(part$lidar_margin),
      median_margin = stats::median(part$lidar_margin),
      row.names = NULL
    )
  }))
}

#' Build a directional LiDAR-versus-rule disagreement audit
#'
#' @param source_dir Directory containing the gut-check files.
#' @param output_dir Directory for generated audit CSVs.
#' @param tier One of the review tiers generated by
#'   `build_knf_gutcheck_record()`.
#' @param metrics Structural metrics to summarize by disagreement type.
#' @return An invisible data frame of eligible point-level diagnostic records.
analyze_knf_gutcheck_disagreement <- function(
    source_dir = "outputs/models",
    output_dir = "outputs/gutcheck_disagreement",
    tier = base::c("all_eligible", "review_not_flagged", "desk_review_flagged"),
    metrics = base::c(
      "zmax", "n_strata_low_mid", "n_gt_6_1",
      "midstory_mean_degree", "understory_mean_betweenness"
    )
) {
  tier <- base::match.arg(tier)
  if (!base::exists("build_knf_gutcheck_record", mode = "function")) {
    base::stop("Source dev/gutcheck_validation_record.R before running this script.", call. = FALSE)
  }
  record <- build_knf_gutcheck_record(
    source_dir = source_dir,
    output_dir = base::file.path(output_dir, "comparison_record")
  )
  data <- record$points
  if (!base::all(metrics %in% base::names(data))) {
    base::stop("All requested metrics must be present in the joined gut-check layer.", call. = FALSE)
  }
  tier_rows <- base::switch(tier,
    all_eligible = data$eligible_three_class_comparison,
    review_not_flagged = data$eligible_three_class_comparison & data$review_status == "not_flagged",
    desk_review_flagged = data$eligible_three_class_comparison & data$review_status == "desk_review_flagged"
  )
  data <- data[tier_rows, , drop = FALSE]
  probabilities <- data[, base::c("msf", "se", "si"), drop = FALSE]
  data$lidar_confidence <- base::apply(probabilities, 1L, base::max)
  data$lidar_entropy <- .normalized_entropy(probabilities)
  data$lidar_margin <- .probability_margin(probabilities)
  data$case_type <- .disagreement_case_type(data$field_class, data$rule_class, data$lidar_class)
  data$prediction_direction <- base::ifelse(
    data$rule_class == data$lidar_class,
    "Models agree",
    base::paste0("Rule ", data$rule_class, " -> LiDAR ", data$lidar_class)
  )
  data$field_direction <- base::paste0("Field ", data$field_class, "; ", data$prediction_direction)

  if (!base::dir.exists(output_dir)) base::dir.create(output_dir, recursive = TRUE)
  by_case <- .disagreement_summary(data, "case_type")
  by_direction <- .disagreement_summary(data, base::c("field_class", "prediction_direction"))
  metric_summary <- base::do.call(base::rbind, base::lapply(metrics, function(metric) {
    groups <- base::split(data[[metric]], data$case_type)
    base::data.frame(
      metric = metric, case_type = base::names(groups), n = base::lengths(groups),
      mean = base::vapply(groups, base::mean, base::numeric(1)),
      median = base::vapply(groups, stats::median, base::numeric(1)),
      sd = base::vapply(groups, stats::sd, base::numeric(1)),
      stringsAsFactors = FALSE, row.names = NULL
    )
  }))
  utils::write.csv(data, base::file.path(output_dir, base::paste0(tier, "_point_audit.csv")), row.names = FALSE)
  utils::write.csv(by_case, base::file.path(output_dir, base::paste0(tier, "_case_summary.csv")), row.names = FALSE)
  utils::write.csv(by_direction, base::file.path(output_dir, base::paste0(tier, "_direction_summary.csv")), row.names = FALSE)
  utils::write.csv(metric_summary, base::file.path(output_dir, base::paste0(tier, "_metric_summary.csv")), row.names = FALSE)
  lines <- base::c(
    "# KNF rule-versus-LiDAR disagreement audit",
    "",
    "This diagnostic identifies the direction of rule-model and LiDAR-GBM disagreement at gut-check points. It must be interpreted against stand-derived field calls, review status, imagery, disturbance history, and map age; it is not pixel-level truth or causal evidence.",
    "",
    "## Case types",
    "",
    "- `Both correct`: both models agree with the three-class field call.",
    "- `LiDAR correct; rule wrong`: the priority set for understanding LiDAR-added structural evidence.",
    "- `Rule correct; LiDAR wrong`: the priority set for identifying LiDAR failure modes, label ambiguity, stale LiDAR, or missing predictors.",
    "- `Both wrong; same call`: likely shared limitation, crosswalk issue, label ambiguity, or a condition neither model represents well.",
    "- `Both wrong; different calls`: strongest disagreement / QA candidates.",
    "",
    "## Uncertainty fields",
    "",
    "- `lidar_confidence`: largest of P(MSF), P(SE), and P(SI).",
    "- `lidar_entropy`: normalized Shannon entropy of all three probabilities; values nearer one mean the probability distribution is more even and uncertain.",
    "- `lidar_margin`: highest probability minus second-highest probability; values nearer zero mean the top two classes are difficult to distinguish.",
    "",
    "## Outputs",
    "",
    "- `*_point_audit.csv`: field/rule/LiDAR classes, probabilities, uncertainty, review status, metrics, and directional case type.",
    "- `*_case_summary.csv`: counts and uncertainty summarized by case type.",
    "- `*_direction_summary.csv`: the same information by observed class and rule-to-LiDAR transition.",
    "- `*_metric_summary.csv`: structural-metric distributions by case type. These are descriptive, not causal effects."
  )
  base::writeLines(lines, base::file.path(output_dir, "README.md"))
  base::invisible(base::structure(
    data, tier = tier, metrics = metrics, class = c("gutcheck_disagreement", "data.frame")
  ))
}

#' Plot LiDAR uncertainty by rule-versus-LiDAR disagreement type
#'
#' @param audit Output from `analyze_knf_gutcheck_disagreement()`.
#' @return A ggplot object.
plot_gutcheck_disagreement_uncertainty <- function(audit) {
  if (!inherits(audit, "gutcheck_disagreement")) {
    base::stop("audit must come from analyze_knf_gutcheck_disagreement().", call. = FALSE)
  }
  long <- base::rbind(
    base::data.frame(case_type = audit$case_type, measure = "LiDAR confidence", value = audit$lidar_confidence),
    base::data.frame(case_type = audit$case_type, measure = "Normalized entropy", value = audit$lidar_entropy),
    base::data.frame(case_type = audit$case_type, measure = "Top-two probability margin", value = audit$lidar_margin)
  )
  ggplot2::ggplot(long, ggplot2::aes(x = case_type, y = value, fill = case_type)) +
    ggplot2::geom_boxplot(outlier.alpha = 0.3) +
    ggplot2::facet_wrap(~measure, scales = "free_y") +
    ggplot2::labs(
      title = "LiDAR uncertainty by comparison outcome",
      subtitle = "High entropy and low margin indicate an uncertain LiDAR call.",
      x = NULL, y = NULL, fill = NULL
    ) +
    ggplot2::theme_minimal(base_size = 12) +
    ggplot2::theme(axis.text.x = ggplot2::element_text(angle = 20, hjust = 1), legend.position = "none")
}

