#' Plot counts of each rule-versus-LiDAR comparison outcome
#'
#' @param audit Output from `analyze_knf_gutcheck_disagreement()`.
#' @return A ggplot object.
plot_gutcheck_disagreement_counts <- function(audit) {
  if (!inherits(audit, "gutcheck_disagreement")) {
    base::stop("audit must come from analyze_knf_gutcheck_disagreement().", call. = FALSE)
  }
  counts <- base::as.data.frame(base::table(audit$case_type), stringsAsFactors = FALSE)
  base::names(counts) <- base::c("case_type", "n")
  counts$case_type <- base::factor(counts$case_type, levels = counts$case_type[base::order(counts$n)])
  ggplot2::ggplot(counts, ggplot2::aes(x = case_type, y = n, fill = case_type)) +
    ggplot2::geom_col(show.legend = FALSE) +
    ggplot2::geom_text(ggplot2::aes(label = n), hjust = -0.15, size = 4) +
    ggplot2::coord_flip(clip = "off") +
    ggplot2::scale_y_continuous(expand = ggplot2::expansion(mult = c(0, 0.12))) +
    ggplot2::labs(
      title = "Where the KNF rule model and LiDAR GBM agree or disagree",
      subtitle = "Matched gut-check points with a three-class field call and both model predictions.",
      x = NULL, y = "Number of points"
    ) +
    ggplot2::theme_minimal(base_size = 13)
}

#' Plot field-call confusion matrices for the rule model and LiDAR GBM
#'
#' @param audit Output from `analyze_knf_gutcheck_disagreement()`.
#' @return A ggplot object.
plot_gutcheck_comparison_confusion <- function(audit) {
  if (!inherits(audit, "gutcheck_disagreement")) {
    base::stop("audit must come from analyze_knf_gutcheck_disagreement().", call. = FALSE)
  }
  classes <- base::c("msf", "se", "si")
  one_model <- function(prediction, model_name) {
    out <- base::as.data.frame(base::table(
      field_class = base::factor(audit$field_class, levels = classes),
      predicted_class = base::factor(audit[[prediction]], levels = classes)
    ), stringsAsFactors = FALSE)
    base::names(out)[3L] <- "n"
    out$model <- model_name
    out$row_total <- stats::ave(out$n, out$field_class, FUN = base::sum)
    out$percent_of_field_class <- ifelse(out$row_total > 0, out$n / out$row_total, NA_real_)
    out
  }
  data <- base::rbind(
    one_model("rule_class", "KNF rule model"),
    one_model("lidar_class", "LiDAR GBM")
  )
  ggplot2::ggplot(data, ggplot2::aes(x = predicted_class, y = field_class, fill = percent_of_field_class)) +
    ggplot2::geom_tile(color = "white", linewidth = 0.8) +
    ggplot2::geom_text(ggplot2::aes(label = base::paste0(n, "\n", base::sprintf("%.0f%%", 100 * percent_of_field_class))), size = 4) +
    ggplot2::facet_wrap(~model) +
    ggplot2::scale_fill_viridis_c(labels = scales::label_percent(accuracy = 1)) +
    ggplot2::labs(
      title = "Field-stage calls versus model predictions",
      subtitle = "Rows sum to 100% within each field-labeled class. Diagonal cells are agreement.",
      x = "Model prediction", y = "Recorded field stage", fill = "Within-field class"
    ) +
    ggplot2::theme_minimal(base_size = 13)
}

#' Plot rule-to-LiDAR transition counts within field classes
#'
#' @param audit Output from `analyze_knf_gutcheck_disagreement()`.
#' @return A ggplot object.
plot_gutcheck_prediction_transitions <- function(audit) {
  if (!inherits(audit, "gutcheck_disagreement")) {
    base::stop("audit must come from analyze_knf_gutcheck_disagreement().", call. = FALSE)
  }
  data <- audit[audit$prediction_direction != "Models agree", , drop = FALSE]
  counts <- base::as.data.frame(base::table(data$field_class, data$prediction_direction), stringsAsFactors = FALSE)
  base::names(counts) <- base::c("field_class", "prediction_direction", "n")
  counts <- counts[counts$n > 0L, , drop = FALSE]
  ggplot2::ggplot(counts, ggplot2::aes(x = stats::reorder(prediction_direction, n), y = n, fill = prediction_direction)) +
    ggplot2::geom_col(show.legend = FALSE) +
    ggplot2::geom_text(ggplot2::aes(label = n), hjust = -0.15, size = 3.5) +
    ggplot2::coord_flip(clip = "off") +
    ggplot2::facet_wrap(~field_class, scales = "free_y") +
    ggplot2::scale_y_continuous(expand = ggplot2::expansion(mult = c(0, 0.12))) +
    ggplot2::labs(
      title = "Direction of rule-versus-LiDAR disagreement",
      subtitle = "Only points where the two models give different structural-stage calls.",
      x = NULL, y = "Number of points"
    ) +
    ggplot2::theme_minimal(base_size = 12)
}

#' Plot agreement and disagreement outcomes within each field class
#'
#' @param audit Output from `analyze_knf_gutcheck_disagreement()`.
#' @return A ggplot object.
plot_gutcheck_outcome_by_field_class <- function(audit) {
  if (!inherits(audit, "gutcheck_disagreement")) {
    base::stop("audit must come from analyze_knf_gutcheck_disagreement().", call. = FALSE)
  }
  classes <- base::c("msf", "se", "si")
  outcomes <- base::c(
    "Both correct", "LiDAR correct; rule wrong", "Rule correct; LiDAR wrong",
    "Both wrong; same call", "Both wrong; different calls"
  )
  data <- base::as.data.frame(base::table(
    field_class = base::factor(audit$field_class, levels = classes),
    case_type = base::factor(audit$case_type, levels = outcomes)
  ), stringsAsFactors = FALSE)
  base::names(data)[3L] <- "n"
  data$total <- stats::ave(data$n, data$field_class, FUN = base::sum)
  data$proportion <- data$n / data$total
  ggplot2::ggplot(data, ggplot2::aes(x = case_type, y = field_class, fill = proportion)) +
    ggplot2::geom_tile(color = "white", linewidth = 0.8) +
    ggplot2::geom_text(ggplot2::aes(label = base::paste0(n, "\n", base::sprintf("%.0f%%", 100 * proportion))), size = 3.6) +
    ggplot2::scale_fill_viridis_c(labels = scales::label_percent(accuracy = 1)) +
    ggplot2::labs(
      title = "Agreement and disagreement within each recorded field class",
      subtitle = "Rows sum to 100%. This shows where each product's successes and errors occur.",
      x = NULL, y = "Recorded field stage", fill = "Within-field class"
    ) +
    ggplot2::theme_minimal(base_size = 12) +
    ggplot2::theme(axis.text.x = ggplot2::element_text(angle = 25, hjust = 1))
}

#' Plot structural and uncertainty profiles of agreement/disagreement outcomes
#'
#' @param audit Output from `analyze_knf_gutcheck_disagreement()`.
#' @return A ggplot object.
plot_gutcheck_outcome_profiles <- function(audit) {
  if (!inherits(audit, "gutcheck_disagreement")) {
    base::stop("audit must come from analyze_knf_gutcheck_disagreement().", call. = FALSE)
  }
  variables <- base::c(attr(audit, "metrics"), "lidar_entropy", "lidar_margin")
  labels <- base::c(
    zmax = "Maximum height", n_strata_low_mid = "Low-mid layering",
    n_gt_6_1 = "Vegetation > 6.1 m", midstory_mean_degree = "Midstory connectivity",
    understory_mean_betweenness = "Understory betweenness",
    lidar_entropy = "LiDAR uncertainty (entropy)", lidar_margin = "LiDAR separation (margin)"
  )
  outcomes <- base::c(
    "Both correct", "LiDAR correct; rule wrong", "Rule correct; LiDAR wrong",
    "Both wrong; same call", "Both wrong; different calls"
  )
  rows <- base::do.call(base::rbind, base::lapply(variables, function(variable) {
    overall_median <- stats::median(audit[[variable]], na.rm = TRUE)
    overall_sd <- stats::sd(audit[[variable]], na.rm = TRUE)
    groups <- base::split(audit[[variable]], audit$case_type)
    base::data.frame(
      variable = variable, case_type = base::names(groups),
      standardized_median_difference = base::vapply(groups, function(values) {
        (stats::median(values, na.rm = TRUE) - overall_median) / overall_sd
      }, base::numeric(1)),
      stringsAsFactors = FALSE, row.names = NULL
    )
  }))
  rows$case_type <- base::factor(rows$case_type, levels = outcomes)
  rows$variable <- base::factor(rows$variable, levels = variables, labels = labels[variables])
  ggplot2::ggplot(rows, ggplot2::aes(x = case_type, y = variable, fill = standardized_median_difference)) +
    ggplot2::geom_tile(color = "white", linewidth = 0.8) +
    ggplot2::geom_text(ggplot2::aes(label = base::sprintf("%+.1f", standardized_median_difference)), size = 3.8) +
    ggplot2::scale_fill_gradient2(low = "#2C7BB6", mid = "white", high = "#D7191C", midpoint = 0,
      name = "Median relative\nto all points\n(SD units)") +
    ggplot2::labs(
      title = "What distinguishes agreement and disagreement groups?",
      subtitle = "Values show each group's median relative to the full holdout set. They describe patterns, not causal effects.",
      x = NULL, y = NULL
    ) +
    ggplot2::theme_minimal(base_size = 12) +
    ggplot2::theme(axis.text.x = ggplot2::element_text(angle = 25, hjust = 1))
}

#' Save presentation-ready gut-check disagreement figures
#'
#' @param audit Output from `analyze_knf_gutcheck_disagreement()`.
#' @param output_dir Directory for PNG figures.
#' @param prefix File-name prefix.
#' @param dpi Resolution for PNG figures. Use 600 for clear zooming and print.
#' @return An invisible named vector of figure paths.
save_gutcheck_disagreement_figures <- function(
    audit,
    output_dir = "outputs/gutcheck_disagreement/figures",
    prefix = "all_eligible",
    dpi = 600
) {
  if (!inherits(audit, "gutcheck_disagreement")) {
    base::stop("audit must come from analyze_knf_gutcheck_disagreement().", call. = FALSE)
  }
  if (!base::dir.exists(output_dir)) base::dir.create(output_dir, recursive = TRUE)
  plots <- base::list(
    comparison_outcomes = plot_gutcheck_disagreement_counts(audit),
    comparison_confusion = plot_gutcheck_comparison_confusion(audit),
    prediction_transitions = plot_gutcheck_prediction_transitions(audit),
    outcome_by_field_class = plot_gutcheck_outcome_by_field_class(audit),
    outcome_profiles = plot_gutcheck_outcome_profiles(audit),
    lidar_uncertainty = plot_gutcheck_disagreement_uncertainty(audit),
    structural_metrics = plot_gutcheck_disagreement_metrics(audit)
  )
  dimensions <- base::list(
    comparison_outcomes = base::c(11, 7), comparison_confusion = base::c(12, 7),
    prediction_transitions = base::c(13, 8), lidar_uncertainty = base::c(13, 8),
    structural_metrics = base::c(14, 9), outcome_by_field_class = base::c(13, 7),
    outcome_profiles = base::c(14, 8)
  )
  if (!base::is.numeric(dpi) || base::length(dpi) != 1L || !base::is.finite(dpi) || dpi < 72) {
    base::stop("dpi must be one finite numeric value of at least 72.", call. = FALSE)
  }
  png_paths <- base::vapply(base::names(plots), function(name) {
    path <- base::file.path(output_dir, base::paste0(prefix, "_", name, ".png"))
    ggplot2::ggsave(
      filename = path, plot = plots[[name]], width = dimensions[[name]][1L],
      height = dimensions[[name]][2L], units = "in", dpi = dpi, bg = "white"
    )
    path
  }, base::character(1))
  svg_paths <- base::vapply(base::names(plots), function(name) {
    path <- base::file.path(output_dir, base::paste0(prefix, "_", name, ".svg"))
    result <- base::try(ggplot2::ggsave(
      filename = path, plot = plots[[name]], width = dimensions[[name]][1L],
      height = dimensions[[name]][2L], units = "in", bg = "white"
    ), silent = TRUE)
    if (inherits(result, "try-error")) NA_character_ else path
  }, base::character(1))
  base::invisible(base::list(png = png_paths, svg = svg_paths))
}

